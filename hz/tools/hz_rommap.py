#!/usr/bin/env python3
"""(Session 78) src/extract/rom_map.h from hz.sym: where in the original ROM
the game's own extractor (src/extract/, in C) finds what it reads.

    python3 tools/hz_rommap.py           write src/extract/rom_map.h
    python3 tools/hz_rommap.py --check   exit 1 unless it is hz.sym's

hz.sym is the disassembly's symbols (`make rom` writes it; checked in), so
the header names each block as asm/hz.asm does: EXR_UnitStats is
UnitStats's address. Only the labels in NAMES go in, the ones the
extractor reads; tools/hz_extract.py, its reference, reads the same ones by
name. Addresses only: the header holds nothing of the ROM's bytes. `make
assets_check` runs --check first.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.join(HERE, '..')
SYM = os.path.join(TOP, 'hz.sym')
OUT = os.path.join(TOP, 'src', 'extract', 'rom_map.h')

NAMES = [
    'CPUStartTypeTable', 'ColourCycles', 'CopyrightCycle', 'CopyrightPalette',
    'DemoData', 'DemoTable', 'EndingPaletteGrave', 'EndingPaletteStillLife',
    'EndingText1', 'EndingText2', 'EndingTextPalette', 'ExplosionFrames',
    'FontTiles', 'ForestPalette', 'GamePalettes', 'HUDFrameTiles',
    'HUDIcons', 'HUDTiles', 'M_SfxCount', 'MapNames', 'MapPalettes',
    'Map_AnimTilesUpdate',
    'MechFrames', 'MenuPalette', 'MusicTestRepeat', 'MusicTitles',
    'OrderInfo', 'RLE_EndingPictures', 'RLE_MenuGfx', 'RLE_TankPhotos',
    'RLE_WinnerFont', 'RadarImages', 'SegaLogoCycle', 'SegaLogoPalette',
    'SfxPriority', 'SoundData', 'SpriteTiles', 'StaffCopyrightJapan',
    'StaffCopyrightOverseas', 'StaffText', 'StartUnits', 'TankPhotoPalette',
    'UnitAvailByMap', 'UnitDirTable', 'UnitStats', 'UnitStats_KIDOU',
    'WinnerPalette', 'WinnerPhotoPalette',
    'pack_forest', 'pack_map_blocks', 'pack_map_layout', 'pack_map_tiles',
]


def header():
    labels = {}
    for line in open(SYM, encoding='utf-8'):
        f = line.split()
        if len(f) == 2 and f[1].startswith('$'):
            labels[f[0]] = int(f[1][1:], 16)
    missing = [n for n in NAMES if n not in labels]
    if missing:
        sys.exit('hz.sym has no %s' % ', '.join(missing))
    lines = [
        '/* Generated by tools/hz_rommap.py from hz.sym (the disassembly\'s',
        ' * symbols): where the original ROM keeps what src/extract/ reads,',
        ' * by asm/hz.asm\'s names. Addresses only. Do not edit; `make',
        ' * rom_map` writes it again when a label moves. */',
        '#ifndef HZ_ROM_MAP_H',
        '#define HZ_ROM_MAP_H',
        '',
    ]
    width = max(len(n) for n in NAMES) + 4
    for n in sorted(NAMES, key=str.lower):
        lines.append('#define %-*s 0x%06Xu' % (width, 'EXR_' + n, labels[n]))
    lines += ['', '#endif /* HZ_ROM_MAP_H */', '']
    return '\n'.join(lines)


def main():
    text = header()
    if sys.argv[1:] == ['--check']:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) \
            else ''
        if have != text:
            print('src/extract/rom_map.h is not hz.sym\'s: make rom_map')
            return 1
        print('src/extract/rom_map.h: hz.sym\'s (%d labels)' % len(NAMES))
        return 0
    if sys.argv[1:]:
        print(__doc__)
        return 2
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('%s: %d labels' % (OUT, len(NAMES)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
